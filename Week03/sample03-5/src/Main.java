void main() {
    String name = "홍길동";
    double height = 170.6;
    double weight = 67.5;
    int age = 21;
    String gender = "남자";

    System.out.printf("%s의 키는 %.1fCm 입니다.\n", name, height);
    System.out.printf("%s의 몸무게는 %.1fKg 입니다.\n", name, weight);
    System.out.printf("%s의 나이는 %d살 입니다.\n", name, age);
    System.out.printf("%s은 %s입니다.\n", name, gender);
}
